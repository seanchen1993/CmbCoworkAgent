-- Internal read-only requirement queue. Exactly one attempt, no recovery/fallback.
-- Command keys are internal enqueue keys, not public command_receipts.
CREATE TABLE requirement_run_queue (
  space_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  requester_principal_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  command_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  fingerprint BINARY(32) NOT NULL,
  group_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  task_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stage_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  bot_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  bot_version_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  node_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  owner_principal_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  grant_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  workspace_ref VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  task_version BIGINT NOT NULL,
  group_version BIGINT NOT NULL,
  node_version BIGINT NOT NULL,
  grant_version BIGINT NOT NULL,
  version BIGINT NOT NULL,
  initial_status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  deadline DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  attempt_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  fence BIGINT NULL,
  lease_expires_at DATETIME(3) NULL,
  PRIMARY KEY (space_id,id),
  UNIQUE KEY uq_requirement_enqueue (space_id,requester_principal_id,command_id),
  KEY ix_requirement_group_status (space_id,group_id,status),
  KEY ix_requirement_node_status (space_id,node_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

#!/usr/bin/env bash
# Explicitly authorized one-off repair inside the owned guest, never provision.
set -Eeuo pipefail
umask 077
task_owner=${1:?owner UUID required}
[[ "$task_owner" =~ ^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$ ]]
[[ $(id -u) = 0 && $(hostname) = colima-devclaw-bot ]]
[[ $(ip -4 -o addr show dev eth0 | awk '{print $4}') = 192.168.5.1/24 ]]
[[ -L /etc/resolv.conf && $(readlink /etc/resolv.conf) = ../run/systemd/resolve/stub-resolv.conf ]]
[[ $(stat -c %u /etc/resolv.conf) = 0 && ! -e /etc/resolv.conf ]]
[[ ! -e /etc/dnsmasq.d/01-colima.conf && ! -L /etc/dnsmasq.d/01-colima.conf ]]
[[ $(readlink -f /etc/dnsmasq.d) = /etc/dnsmasq.d && $(stat -c %u /etc/dnsmasq.d) = 0 ]]
[[ $(systemctl show dnsmasq -p ActiveState --value) = failed ]]
backup=/var/lib/devclaw-bot-b00-dns-$task_owner
[[ ! -e "$backup" && ! -L "$backup" ]]
mkdir -m 700 -- "$backup"
cp -a --no-dereference -- /etc/resolv.conf "$backup/resolv.conf.original"
printf '%s\n' "$task_owner" > "$backup/owner"
printf '%s\n' '../run/systemd/resolve/stub-resolv.conf' > "$backup/original-link"
printf '%s\n' 'absent' > "$backup/original-dnsmasq-state"
printf '%s\n' 'failed' > "$backup/original-service-state"
printf '# Generated by Colima\n\nnameserver 192.168.5.1\n' > "$backup/resolv.next"
printf '%s\n' '# Generated by Colima' '' 'address=/host.docker.internal/192.168.5.2' 'address=/host.lima.internal/192.168.5.2' 'address=/colima.internal/192.168.5.1' 'address=/colima-devclaw-bot/127.0.0.1' '' 'server=192.168.5.2' 'interface=eth0' 'listen-address=192.168.5.1' 'bind-interfaces' > "$backup/dnsmasq.next"
resolv_hash=$(sha256sum "$backup/resolv.next" | awk '{print $1}')
dnsmasq_hash=$(sha256sum "$backup/dnsmasq.next" | awk '{print $1}')
chmod 644 -- "$backup/resolv.next" "$backup/dnsmasq.next"
printf '%s\n' "$resolv_hash" > "$backup/resolv.sha256"
printf '%s\n' "$dnsmasq_hash" > "$backup/dnsmasq.sha256"
resolv_changed=0
dnsmasq_changed=0
rollback() {
  local failed=0
  trap - ERR INT TERM
  set +e
  timeout 15 systemctl stop dnsmasq || failed=1
  if ((resolv_changed)); then
    if [[ -f /etc/resolv.conf && ! -L /etc/resolv.conf && $(stat -c %u /etc/resolv.conf) = 0 && $(sha256sum /etc/resolv.conf | awk '{print $1}') = "$resolv_hash" ]]; then
      mv -T -- "$backup/resolv.conf.original" /etc/resolv.conf || failed=1
    else failed=1; fi
  fi
  if ((dnsmasq_changed)); then
    if [[ -f /etc/dnsmasq.d/01-colima.conf && ! -L /etc/dnsmasq.d/01-colima.conf && $(stat -c %u /etc/dnsmasq.d/01-colima.conf) = 0 && $(sha256sum /etc/dnsmasq.d/01-colima.conf | awk '{print $1}') = "$dnsmasq_hash" ]]; then
      rm -- /etc/dnsmasq.d/01-colima.conf || failed=1
    else failed=1; fi
  fi
  printf 'B00_DNS_ROLLBACK result=%s backup=%s\n' "$failed" "$backup"
  exit 1
}
trap rollback ERR INT TERM
mv -T -- "$backup/dnsmasq.next" /etc/dnsmasq.d/01-colima.conf
dnsmasq_changed=1
mv -T -- "$backup/resolv.next" /etc/resolv.conf
resolv_changed=1
timeout 20 systemctl restart dnsmasq
systemctl is-active --quiet dnsmasq
timeout 10 getent ahostsv4 registry-1.docker.io >/dev/null
http_status=$(curl --silent --show-error --connect-timeout 5 --max-time 15 --output /dev/null --write-out '%{http_code}' https://registry-1.docker.io/v2/)
[[ "$http_status" = 401 ]]
trap - ERR INT TERM
printf 'B00_DNS_REPAIRED backup=%s resolver_sha256=%s dnsmasq_sha256=%s registry_tls_http=%s\n' "$backup" "$resolv_hash" "$dnsmasq_hash" "$http_status"

/** Failure recovery is a separate simulated run; the first failure stays in its history. */
export function sparksFlowRecoveryStages(scenario: string): SparksTourExample["stages"] {
  const denied = scenario === "denied"
  return [
    ...sparksTourExamples[3].stages.slice(0, 2),
    {
      title: "失败",
      instruction: "打开“任务进展”，先看失败提示；需要完整记录时展开排查详情。",
      screen: "读取未完成 → 后续检视未执行",
      detail: denied
        ? "第 1 轮示例原因：文件读取未获授权。没有得到文件内容，不能继续检视。"
        : "第 1 轮示例原因：读取前后的需求记录不一致。旧资料不能继续用于检视。"
    },
    {
      title: "排查",
      instruction: "按失败提示检查项目、文件和权限；仍不清楚时，再展开技术详情。",
      screen: denied ? "排查：核对项目、文件路径和读取权限" : "排查：核对最新需求和对应文件",
      detail: denied
        ? "先选对项目和文件，再到插件卡片核对读取权限。"
        : "确认最新需求，再选择对应文件，让下一轮重新读取。"
    },
    {
      title: "模拟修复",
      instruction: "看示例如何处理问题；下一步再重新检查。",
      screen: denied ? "已模拟修正读取条件 · 等待重新验证" : "已模拟核对最新需求 · 等待重新验证",
      detail: "处理问题后，需要重新启动任务。上一轮失败记录仍保留，便于对照。"
    },
    {
      title: "重新运行",
      instruction: "重新启动后，会生成一条新记录，并从读取当前文件开始。",
      screen: "第 2 轮演示：重新读取 → 重新检视",
      detail: "示例展示重新运行的顺序。实际使用时，会读取最新文件并重新给出意见。"
    },
    {
      title: "查看新结果",
      instruction: "分别查看两轮结果；检视发现的问题仍需修复并执行实际测试。",
      screen: "第 2 轮演示结果：读取完成，检视发现空列表风险",
      detail: "检查意见仅供修复参考。项目是否完成，还需通过原有测试和人工确认。"
    }
  ]
}


import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { build, version } from "esbuild"

// Author-time only. Never downloads dependencies or runs package lifecycle scripts.
const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const lock = JSON.parse(
  await readFile(join(repository, "scripts/autobiz-collector-dependency-lock.json"), "utf8")
)
const args = process.argv.slice(2)
const selected = args.indexOf("--dependencies")
const dependencies = resolve(
  selected < 0
    ? join(repository, "output/creator-context-fixture-deps/node_modules")
    : args[selected + 1]
)
const sha = (value) => createHash("sha256").update(value).digest("hex")
if (version !== lock.esbuild) throw Error("AUTOBIZ_COLLECTOR_BUNDLER_VERSION_CHANGED")
for (const [file, digest] of Object.entries(lock.inputs)) {
  if (sha(await readFile(join(dependencies, file))) !== digest)
    throw Error(`AUTOBIZ_COLLECTOR_DEPENDENCY_CHANGED: ${file}`)
}
const result = await build({
  absWorkingDir: dependencies,
  entryPoints: ["gray-matter/index.js"],
  bundle: true,
  write: false,
  platform: "node",
  format: "cjs",
  target: "node18",
  minify: true,
  legalComments: "eof",
  metafile: true,
  banner: {
    js: "/* eslint-disable */\n// Generated by scripts/prepare-autobiz-collector-dependency.mjs. See collector-THIRD-PARTY-NOTICES.md."
  }
})
if (
  JSON.stringify(Object.keys(result.metafile.inputs).sort()) !== JSON.stringify(lock.bundledInputs)
)
  throw Error("AUTOBIZ_COLLECTOR_DEPENDENCY_CLOSURE_CHANGED")
const notices = [
  "# Offline AutoBiz knowledge collector dependencies",
  "",
  "Generated from pinned, locally available packages; no runtime npm installation is needed.",
  "Reproduce with Node 22: node scripts/prepare-autobiz-collector-dependency.mjs --dependencies <node_modules>",
  "Use --check to compare without writing. Input hashes are pinned in scripts/autobiz-collector-dependency-lock.json.",
  "The original collector continues to use gray-matter's YAML safeLoad parser. No YAML parser is reimplemented.",
  ""
]
for (const item of lock.licenses) {
  const text = await readFile(join(dependencies, item.path), "utf8")
  notices.push(`## ${item.package}@${item.version}`, "", text.trim(), "")
}
const files = new Map([
  ["collector-gray-matter.cjs", result.outputFiles[0].text],
  ["collector-THIRD-PARTY-NOTICES.md", notices.join("\n")]
])
for (const [name, content] of files) {
  if (Buffer.byteLength(content) > 64 * 1024) throw Error("AUTOBIZ_COLLECTOR_RESOURCE_LIMIT")
  const target = join(repository, "resources/mods/autobiz-knowledge", name)
  if (args.includes("--check")) {
    if ((await readFile(target, "utf8")) !== content)
      throw Error(`AUTOBIZ_COLLECTOR_GENERATED_DIFF: ${name}`)
  } else await writeFile(target, content)
}
console.log(
  JSON.stringify({
    operation: args.includes("--check") ? "check" : "generate",
    files: [...files].map(([path, text]) => ({
      path,
      bytes: Buffer.byteLength(text),
      sha256: sha(text)
    }))
  })
)

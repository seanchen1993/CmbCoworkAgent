import { build } from "esbuild"
import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const packages = ["whatwg-url", "tr46", "webidl-conversions", "punycode"]
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: 'export { URL, URLSearchParams } from "whatwg-url";',
    resolveDir: root
  },
  bundle: true,
  write: false,
  platform: "browser",
  target: "es2020",
  format: "iife",
  globalName: "__urlExports",
  minify: true,
  legalComments: "none",
  metafile: true,
  plugins: [
    {
      name: "guest-json-data",
      setup(builder) {
        builder.onLoad({ filter: /mappingTable\.json$/ }, async (args) => {
          const json = JSON.stringify(JSON.parse(await readFile(args.path, "utf8")))
          return { contents: `module.exports = JSON.parse(${JSON.stringify(json)})`, loader: "js" }
        })
        // QuickJS compiles large Unicode regexp literals while parsing. Preserve each exact
        // pattern/flag and object identity, but initialize it on the library's first read.
        builder.onLoad({ filter: /tr46[\\/]lib[\\/]regexes\.js$/ }, async (args) => {
          const source = await readFile(args.path, "utf8")
          const patterns = [...source.matchAll(/^const (\w+) = \/(.*)\/([gimsuy]*);\r?$/gm)]
          if (patterns.length !== 12) throw Error("Unexpected locked tr46 regexp declarations")
          const properties = patterns
            .map(
              ([, name, pattern, flags]) =>
                `${JSON.stringify(name)}:{configurable:true,enumerable:true,get(){
            const value=new R(${JSON.stringify(pattern)},${JSON.stringify(flags)});
            define(table,${JSON.stringify(name)},{value,writable:true,configurable:true,enumerable:true});
            return value;
          }}`
            )
            .join(",")
          return {
            contents: `const R=RegExp,define=Object.defineProperty,table={};
            Object.defineProperties(table,{${properties}});module.exports=table`,
            loader: "js"
          }
        })
      }
    }
  ]
})
if (result.outputFiles.length !== 1) throw Error("Unexpected URL bundle output")
if (Object.values(result.metafile.outputs).some((output) => output.imports.length))
  throw Error("URL guest must be self contained")
// Resolve manifests from actual bundled inputs, not top-level hoisting. A future dependency
// tree with nested versions must retain the notices of the code really shipped to the guest.
const bundledPackages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (input === "<stdin>") continue
  let directory = dirname(resolve(root, input))
  while (directory !== root) {
    try {
      const manifest = JSON.parse(await readFile(resolve(directory, "package.json"), "utf8"))
      if (!packages.includes(manifest.name))
        throw Error(`Unexpected bundled dependency: ${manifest.name}`)
      bundledPackages.set(directory, manifest)
      break
    } catch (error) {
      if (error.code !== "ENOENT") throw error
      const parent = dirname(directory)
      if (parent === directory) throw Error(`No package for bundled input: ${input}`)
      directory = parent
    }
  }
  if (directory === root) throw Error(`No package for bundled input: ${input}`)
}
const licenses = []
for (const [directory, manifest] of [...bundledPackages].sort(
  ([, a], [, b]) =>
    packages.indexOf(a.name) - packages.indexOf(b.name) || a.version.localeCompare(b.version)
)) {
  let license
  for (const filename of ["LICENSE", "LICENSE.txt", "LICENSE.md", "LICENSE-MIT.txt"]) {
    try {
      license = await readFile(resolve(directory, filename), "utf8")
      break
    } catch (error) {
      if (error.code !== "ENOENT") throw error
    }
  }
  if (!license) throw Error(`Missing license: ${manifest.name}`)
  licenses.push(`${manifest.name}@${manifest.version} (${manifest.license})\n${license.trim()}\n`)
}
if (
  packages.some((name) => ![...bundledPackages.values()].some((manifest) => manifest.name === name))
)
  throw Error("Missing expected bundled dependency")
const code = `(() => {${result.outputFiles[0].text.trim()};return __urlExports;})()`
const hash = createHash("sha256").update(code).digest("hex")
const outputs = new Map([
  [
    "src/main/mods/v2/guest-url-source.ts",
    `// Generated by scripts/generate-mods-url.mjs; do not edit.\n// SHA256: ${hash}\n// Licenses and dependency versions: guest-url-LICENSE.txt\n/* eslint-disable */\nexport const FUNCTION_URL_GLOBALS = ${JSON.stringify(code)}\n`
  ],
  ["src/main/mods/v2/guest-url-LICENSE.txt", licenses.join("\n---\n\n")]
])
for (const [path, content] of outputs) {
  const file = resolve(root, path)
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== content)
      throw Error(`Generated URL asset stale: ${path}`)
  } else await writeFile(file, content, "utf8")
}
console.log(`URL guest: ${Buffer.byteLength(code)} bytes; sha256 ${hash}`)
